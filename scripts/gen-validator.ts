// Generates a standalone ESM validator (src/model/validate-trip.gen.js + .d.ts) from schema/trip.schema.json,
// so the browser validates trips without compiling the schema at runtime (no Ajv in the bundle, no eval).
// Run with `npm run gen` after changing the schema and commit the result.
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'

const schemaFile = new URL('../schema/trip.schema.json', import.meta.url)
const jsFile = new URL('../src/model/validate-trip.gen.js', import.meta.url)
const dtsFile = new URL('../src/model/validate-trip.gen.d.ts', import.meta.url)

const banner = `/* eslint-disable */
// Generated by scripts/gen-validator.ts from schema/trip.schema.json. Do not edit: run \`npm run gen\`.
`

const dts = `${banner}import type { ErrorObject } from 'ajv'

declare const validate: {
  (data: unknown): boolean
  errors?: ErrorObject[] | null
}
export default validate

/** Every \`pattern\` in the schema → the name of the \`$defs\` entry that contains it (for readable messages). */
export declare const patternDefs: Record<string, string>
`

const require = createRequire(import.meta.url)

function patternDefs(schema: { $defs: Record<string, unknown> }): Record<string, string> {
  const result: Record<string, string> = {}
  const visit = (node: unknown, def: string): void => {
    if (!node || typeof node !== 'object') return
    const { pattern } = node as { pattern?: unknown }
    if (typeof pattern === 'string') result[pattern] ??= def
    Object.values(node).forEach((child) => visit(child, def))
  }
  for (const [name, def] of Object.entries(schema.$defs)) visit(def, name)
  return result
}

export async function generateValidator(): Promise<{ js: string; dts: string }> {
  const schema = JSON.parse(await readFile(schemaFile, 'utf8')) as { $defs: Record<string, unknown> }
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    // The schema uses `anyOf: [{ required: [...] }]`, which strictRequired rejects.
    strictRequired: false,
    code: { source: true, esm: true, lines: true },
  })
  const code = standaloneCode(ajv, ajv.compile(schema))
  // Even in ESM mode Ajv references a few runtime helpers with require() (e.g. ucs2length for minLength).
  // Inline them so the file is plain ESM with no dependency on ajv.
  const js = code.replace(/require\("(ajv\/dist\/runtime\/\w+)"\)\.default/g, (_, mod: string) => {
    return `(${(require(mod) as { default: () => unknown }).default.toString()})`
  })
  if (js.includes('require(')) throw new Error('gen-validator: unexpected require() in output')
  return { js: `${banner}${js}\nexport const patternDefs = ${JSON.stringify(patternDefs(schema), null, 2)}\n`, dts }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { js, dts } = await generateValidator()
  await writeFile(jsFile, js)
  await writeFile(dtsFile, dts)
  console.log('wrote src/model/validate-trip.gen.js and validate-trip.gen.d.ts')
}
